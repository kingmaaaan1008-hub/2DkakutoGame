/**
 * 戦闘メイド — 圧殺型。身の丈ほどある包丁で、縦に潰す。
 *
 *   攻撃: 「横薙ぎ」(attack_h シート) 踏み込んで真横に薙ぐ
 *        続けて攻撃で「叩き割り」(attack_v シート) — 頭上から振り下ろす 2 段目
 *   スキル: 「天空斬り」(aether_rise → aether_slam) 斬り上げながら跳び上がり、
 *          そのまま包丁を叩きつけて降りてくる。上りと下りで 2 回当たる
 *   空中攻撃: 「回転斬り」(spin_slash シート) 体ごと回って、包丁を一周させる
 *   空中スキル: 「天空斬り（落とし）」(aether_slam シート) 天空斬りの下りだけ
 *
 * ── 立ち位置 ───────────────────────────────────────────────────
 * このキャラの技は**どれも判定が縦に長い**。横薙ぎで 44〜194、叩き割りは
 * 26〜208 と、しゃがみ（やられ判定 0〜100）の上から立ちの頭までを
 * 一枚の刃が通る。**しゃがんでもくぐれず、跳んでも上から潰される**。
 *
 * 代わりに**横がまるで足りない**。横薙ぎの実効射程は 238 で、剣士(273)にも
 * キャヴァリア(302)にも届かない。歩きも全キャラで魔法使いに次いで遅い。
 * つまり、こちらの間合いは相手の間合いの内側にあるので、
 * **入られる前に押し返すのではなく、入ってきたところを縦に潰す**キャラになる。
 *
 * そして天空斬りは、出した瞬間から着地するまで**1 秒近く引き返せない**。
 * 跳び上がって落ちてくるまでの軌道は跳んだ時点で決まっていて、
 * 相手はその下からどいてしまえばいい。外せば着地硬直 24 がまるごと残る。
 * 忍者が「当てる場所を先に置く」キャラなら、こちらは
 * **「当てる高さを先に決めて、そこへ落ちる」**キャラになる。
 */
