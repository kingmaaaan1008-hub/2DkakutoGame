/**
 * 格闘娘 — コンボ型。**地上のどの技も次の技でキャンセルできる**代わりに、
 * リーチが全キャラで最も短い。
 *
 *   攻撃: 「刻み突き」(punch1 シート) ⇄ 「打ち抜き」(punch2 シート) を交互に。
 *        **4 打目だけが「波動突き」**で、突きに合わせて波動弾が飛ぶ
 *   スキル: 「サマーソルト」(somersault シート) 蹴り上げながら真上へ跳ぶ
 *   空中攻撃: 「飛び蹴り」(jumpkick シート) **跳んだ弧をそのまま進みながら**蹴る
 *   空中スキル: 「回転かかと落とし」(flipheel シート) 丸まったまま**敵の方へ弧を描いて跳び**、
 *              弧を降り切ったところで**かかとを真下へ振り下ろす**（heelDrop）。
 *              **回っている間は判定が無い**（移動そのものが技）
 *   空中スキル 2 段目: 「飛び足刀」(flykick シート) 回っている最中にもう一度スキルで、
 *              高さを保ったまま真横へ蹴り抜く
 *
 * ── 立ち位置 ───────────────────────────────────────────────────
 * 判定リーチは刻み突き 106 / 打ち抜き 124 で、**このゲームで最も短い**
 * （サキュバスの引っ掻き 126・忍者の回し斬り 152・剣士の横切り 205）。
 * 踏み込みも飛び道具も持たないので、**届く間合いは自分の足で作るしかない**
 * （忍者の回し斬りには 49 の踏み込みが、剣士のタックルには 182 の突進が付く）。
 * やられ判定ぶんを足した実効射程で見ても 144 で、次に短いサキュバスの 164 より 20 短い。
 *
 * その代わり、**振った技を出し切る必要がない**。判定が出たフレームから
 * 技の最後まで、ずっと次の技を受け付けている（`chains`）。他のキャラの連携が
 * 「この技のこの窓だけ」なのに対して、こちらは**技の並びそのものが自由**になる。
 *
 * 空中も、回転（空中スキル 1 段目）と飛び蹴りの間は**互いにキャンセルできる**。
 * ただし**飛び足刀（2 段目）へ抜けたらそこで打ち止め**で、回転へは戻れない。
 * 足刀は高さを保ったまま真横へ抜ける技なので、戻れるようにすると
 * 落ちてこないまま択を掛け続けられてしまう。
 *
 * そのうえで**空中で繋げるのは 3 回まで**（`airChainLimit`）。地上は押し出しが
 * 歯止めになるが、空中にはそれが無いので回数で区切ってある。
 *
 *   地上: 刻み突き → 打ち抜き → 刻み突き → **波動突き**（4 打目）→ また刻み突き…
 *        （どの段からでもスキルでサマーソルトへ抜けられる）
 *   繋ぎ: サマーソルト（当てると相手が浮く）
 *   空中: 回転かかと落とし（弧で跳び込む）⇄ 飛び蹴り。**飛び足刀へ抜けたら打ち止め**
 *
 * ── 4 打目の波動弾 ─────────────────────────────────────────────
 * 突きを続けると **4 の倍数の打で波動弾**（`kiBlast`）が出る。連打の途中で
 * 手を止めれば数え直しになるので、撃つには 3 発ぶん振り切る必要がある。
 * このキャラで唯一の飛び道具だが、**単体では撃てない**ぶん、
 * 撒いて近づけなくする使い方はできない（間合いを詰める理由は消えない）。
 *
 * ── なぜ「浮かせて追う」が成立するか ───────────────────────────
 * このゲームは一発で致命傷なので、コンボは**ダメージのためではなく
 * ヒット数のため**にある（当たった時点で体力は 0 になり、のけぞりが解けた
 * ところで崩れ落ちる）。つまり相手を浮かせたまま追い打ちを重ねられるほど、
 * 「何発入れてから倒したか」が伸びる。
 *
 * サマーソルトに `knockdown` を付けていないのはそのため。ダウンさせると
 * その時点で無敵になり、追撃が全部素通りしてしまう。`launch` だけを付けて
 * **のけぞらせたまま浮かせる**ことで、空中の技が続けて入る。
 * 締め（かかと落とし）だけが `knockdown` を持っていて、そこでコンボが終わる。
 *
 * ── 固めが無限にならない理由 ───────────────────────────────────
 * 刻み突きは発生 6・ガード硬直 9 で、次の技へ繋げるのが 7 フレーム目。
 * 数字の上ではガードを固め続けられるが、1 発ガードさせるたびに相手は
 * `pushBlock`（2.4〜3.0）ぶん押し出される。**リーチが短いので 3〜4 発で自分から間合いを外す**。
 * 固め切るための技ではなく、押し出す前に崩しへ移るかを選ばせるための技になっている。
 *
 * 逆に**当てたときの押し出しは 0.9〜1.4 しかない**。繋ぎ先（サマーソルトの前方 92）が
 * 突きより短いので、当てるたびに押していると自分のコンボが自分で届かなくなる。
 */
