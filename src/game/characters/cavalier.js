/**
 * 串刺しで貫いた相手を保持する位置（自分の足元原点・前方向が正）。
 *
 * 合わせ先は attack3 シートの伸び切った二刀で、足元から見て
 * **前方 80〜168・高さ 120〜155** を一直線に貫いている（アトラスの実測値）。
 * 相手のやられ判定は HOLD.x を中心に ±38 なので、x = 104 なら
 * 胴が 66〜142 に来て、**刃先(168) が背中から 26 突き出る**。
 * 離すと刃が相手の手前で終わって「刺さっていない」画になる。
 * 掴まれた側は renderer.js が必ず手前に描くので、刃の大半は相手の陰に隠れる。
 * **背中から出ている先端だけが刺さっている証拠**になるので、そこを残す。
 *
 * y は「靴の裏と地面の隙間」。42 持ち上げると相手の胴の中心が刃の高さに乗り
 * （相手の身長 198 の中心 ≒ 42 + 99 = 141 で、刃は 120〜155）、
 * 足が地面から離れて「刃に持ち上げられている」ように見える。
 */
