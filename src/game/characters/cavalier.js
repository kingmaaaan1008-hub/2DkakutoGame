/**
 * キャヴァリア — 機動型。スラスターで距離を潰し、双ビームサーベルで切り抜ける。
 *
 *   攻撃: 「切り抜け」(attack5シート) 飛びながら斬り抜ける。踏み込みが技そのもの。
 *        続けて攻撃で「後退ブースト」(jumpシート) — 斬らずに跳び退く後始末
 *   スキル: 「串刺し」(attack3シート) 掴み。二刀で貫いて持ち上げる
 *   空中攻撃: 「切り抜け」 地上と同じ技。高度を保ったまま横に切り抜ける
 *   空中スキル: 「錐揉み突進」(attack2シート) 水平に長く突っ込む。
 *              もう一度スキルで「宙返り降下」(attackシート)へ切り替えて降りられる
 *
 * ── 立ち位置 ───────────────────────────────────────────────────
 * このキャラは**間合いを詰める技を別に持たない**。攻撃そのものが切り抜けで、
 * 振る＝踏み込むになっている。だから「近づいてから振る」ではなく
 * **「振れる位置に来た瞬間に振り切る」**キャラで、置き技として振ると自分から
 * 相手の前へ飛び込むことになる。
 *
 * 代わりに、どの技も**真っ直ぐで長い一本の線**を引く。読まれた側は下がる必要が無く、
 * 跳ぶかガードして待てば通り過ぎたところを差し返せる。
 * サキュバスがガードに勝ってジャンプに負けるのに対して、こちらは
 * **距離に勝って、待ちに負ける**。
 */
