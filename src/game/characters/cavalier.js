/**
 * 刻みの判定ひとつ分。**ガガガガと連続で当たる中間の 1 発**。
 *
 * このゲームは一発が即死なので、多段はダメージのためではなく手応えのためにある。
 * 1 発ごとに火花とヒットストップが入り、HIT カウントが伸びていく
 * （狂戦士の乱舞と同じ考え方）。
 *
 * 締めの 1 発だけは別に書く。刻みは相手をその場に留めておきたいので
 * 押し出しをほとんど付けず、飛ばすのは最後だけにしてある。
 *
 * `hitstop` が 3 なのは、刻みの間隔（3 フレーム）と釣り合わせるため。
 * ヒットストップの間は攻撃側のフレームも止まるので、ここを大きくすると
 * 刻みが伸びて「ガ……ガ……」と間延びする。
 *
 * @param {number} start 判定の出るフレーム
 * @param {number} group 多段の何発目か（同じ group は 1 度しか当たらない）
 * @param {Box} box 判定範囲
 * @param {object} [extra] 上書きしたい項目（ガード不能など）
 */
function grind(start, group, box, extra = {}) {
  return {
    start,
    end: start + 1,
    box,
    group,
    damage: 24,
    hitstun: 16,
    blockstun: 8,
    hitstop: 3,
    pushHit: 0.8,
    pushBlock: 0.6,
    ...extra,
  };
}

/**
 * ビームサーベルの光の色（'r,g,b'）。
 *
 * 技データの `spawns` で撒く斬撃の帯に使う。既定の斬撃は鋼の刃を想定した
 * 薄い青なので、そのままだとビームに見えない。
 */
const BEAM = '120, 240, 255';

/**
 * 斬撃の帯ひとつ分。**刃の届く先を見せるためのもの**。
 *
 * 刃が薄れるコマの穴埋めは弧の仕事ではない。そちらは発光層
 * （`beamGlow` ／ `src/render/beamglow.js`）が刃そのものを光らせて受け持つ。
 * 弧に任せていた頃は、白い芯の入った帯が振るたび前へ出て、
 * **刃ではなく帯のほうが攻撃の絵に見えてしまっていた**。
 *
 * だからここに残っているのは「絵の刃より判定が先まで出ている技」だけ
 * （串刺しの突きと錐揉みの回転）。一番よく振る切り抜けには付けない。
 *
 * 判定の無い技（後退ブースト・宙返り降下）にも**付けない**。
 * 光の弧は「ここに攻撃判定がある」という合図でもあるので、
 * 当たらない技に付けると嘘になる。
 *
 * @param {number} frame 出すフレーム
 * @param {number} length 前方への長さ
 * @param {number} halfHeight 弧の縦半径
 * @param {{x:number,y:number}} origin 弧の中心（足元原点・前方向が正）
 * @param {number} duration 見えている時間
 */
function beamArc(frame, length, halfHeight, origin, duration = 8) {
  return { frame, type: 'slash', duration, origin, length, halfHeight, tint: BEAM };
}

