/**
 * 忍者 — 設置と撹乱型。踏ませて、消えて、渦になる。
 *
 *   攻撃: 「回し斬り」(run → attack_twirl シート) 一歩踏み込んでから鎌を回す
 *   スキル: 「煙玉」(attack_smoke シート) 3 秒間その場から姿を消す。**判定を持たない**
 *   空中攻撃: 「まきびし」(fall シート) 落ちながら 3 つこぼす。踏むと当たる
 *   空中スキル: 「竜巻」(attack_spin シート) 1 秒かけて回転を上げ、
 *              最高速になったら 2 秒間どこへでも飛べる
 *
 * ── 立ち位置 ───────────────────────────────────────────────────
 * 他のキャラは「振った技が当たるか」で勝負が決まる。忍者だけが
 * **技を出す時点と当たる時点が離れている**キャラで、置いたまきびしと、
 * 消えている間に取り直した位置が仕事をする。
 *
 * その代わり、振り合いそのものは全キャラで一番弱い。
 * 回し斬りは実効射程 239（剣士 273・キャヴァリア 302）しかなく、
 * スキルにいたっては**攻撃判定を 1 つも持たない**。
 * ガードを崩す手段が無いので、固めてくる相手には
 * 「まきびしで下がれなくしてから回し斬り」か、「竜巻で上から潰す」しかない。
 *
 * 女子高生が「当てるのを飛び道具に任せる」キャラなら、忍者は
 * **「当てるのを相手の足に任せる」**キャラになる。
 */
