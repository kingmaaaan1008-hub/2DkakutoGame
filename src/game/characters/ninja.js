/** 見た目の身長（ワールド単位）。ジャンプ高もここから決める。 */
const HEIGHT = 210;

/**
 * 回し斬りの判定範囲。
 *
 * 合わせ先は attack_twirl シートの実測で、突き出した拳のまわりを鎌が回り、
 * 刃先は**前方 134**（f0/f4）まで、上は 221（f3/f7）まで届く。
 * 判定はそれよりわずかに先の 152 までにしてある。
 *
 * 下端 62 は**しゃがみに当てるため**。しゃがみのやられ判定は 0〜100 なので、
 * ここを 100 以上にすると、しゃがまれただけで空振りになる
 * （しゃがみはビームをくぐるための姿勢で、打撃をよける手段ではない）。
 */
const TWIRL_BOX = { x: 20, y: 62, w: 132, h: 140 };

/**
 * 竜巻の判定範囲。
 *
 * attack_spin シートは体ごと 1 回転する絵で、刃は腰から胸の高さを
 * **前にも後ろにも**薙ぐ（実測で x -85〜145 / y 1〜216）。
 * 回っているものに前後は無いので、判定も体の両側に取る。
 *
 * 下端 44 は回し斬りと同じ理由（しゃがみに当てる）。
 */
const DRILL_BOX = { x: -95, y: 44, w: 240, h: 160 };

/**
 * 竜巻の刻みひとつ分。
 *
 * 一発が即死なので、多段はダメージのためではなく手応えのためにある
 * （狂戦士の乱舞・キャヴァリアの錐揉みと同じ考え方）。
 * 刻みには `knockdown` を付けない。ダウンさせるとその時点で無敵になり、
 * 2 発目以降が素通りしてしまう。
 *
 * スキルなので `guardBreak` は全段に付く。
 */
function grind(start, group) {
  return {
    start,
    end: start + 1,
    box: DRILL_BOX,
    group,
    damage: 26,
    hitstun: 16,
    blockstun: 8,
    hitstop: 3,
    pushHit: 1.0,
    pushBlock: 0.8,
    guardBreak: true,
  };
}

/**
 * 竜巻の回転の立ち上がり 1 段ぶん。
 *
 * **絵の速さは技データからしか変えられない**（`animFps` は技ごとに 1 個）ので、
 * 「徐々に速くなる」は段を分けて書く。3 段 × 20 ティック ＝ ちょうど 1 秒で
 * 最高速に届き、そこから本体（tornadoRide）へ繋がる。
 *
 * この 1 秒は**判定をひとつも持たない**。魔法使いの照射の溜めと同じ役割で、
 * 「これから来る」と見せるための時間になっている。そのぶん、
 * 空中で 1 秒まったくの無防備になる。
 *
 * @param {string} next 繋ぎ先
 * @param {number} fps 絵の回転速度
 * @param {number} from この段の始めの渦の強さ
 * @param {number} to この段の終わりの渦の強さ
 */
function windUp(next, fps, from, to) {
  return {
    label: '竜巻',
    anim: 'attack_spin',
    total: 20,
    animFps: fps,
    // 8 コマで 1 回転する閉じたシートなので、回し続けても継ぎ目が出ない
    animLoop: true,
    // その場でぴたりと止まって回転を上げる。vx: 0 で跳んだ勢いも殺す
    // （回りながら流れていくと、溜めているのか突っ込んでいるのか読めない）
    motion: [{ start: 0, end: 19, vx: 0, vy: 0 }],
    vfx: { type: 'tornado', power: from, powerTo: to },
    onEnd: next,
    landLag: 20,
  };
}

